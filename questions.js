export const QUESTION_MAP = new Map(QUESTION_BANK.map(q => [q.id, q]));

export function getQuestionById(id) {
  return QUESTION_MAP.get(id) || null;
}

/**
 * Selects exactly 10 UNIQUE questions from the bank for a match:
 * - Balanced categories (no category repeated more than once).
 * - Balanced difficulty distribution (~3 easy, 5 medium, 2 hard).
 * - Freshly shuffled for every new match or rematch.
 */
export function selectMatchQuestions() {
  // Group questions by category
  const categories = [...new Set(QUESTION_BANK.map(q => q.category))];
  
  // Shuffle categories to get 10 distinct categories
  const shuffledCategories = [...categories].sort(() => Math.random() - 0.5).slice(0, 10);

  // Target difficulty distribution: 3 easy, 5 medium, 2 hard
  const desiredDifficulties = ['easy', 'easy', 'easy', 'medium', 'medium', 'medium', 'medium', 'medium', 'hard', 'hard'];
  const shuffledDiffs = [...desiredDifficulties].sort(() => Math.random() - 0.5);

  const selectedQuestions = [];
  const usedIds = new Set();

  for (let i = 0; i < 10; i++) {
    const cat = shuffledCategories[i];
    const targetDiff = shuffledDiffs[i];

    // Try finding matching category + difficulty
    let candidates = QUESTION_BANK.filter(q => q.category === cat && q.difficulty === targetDiff && !usedIds.has(q.id));
    if (candidates.length === 0) {
      // Fallback to any difficulty in that category
      candidates = QUESTION_BANK.filter(q => q.category === cat && !usedIds.has(q.id));
    }
    if (candidates.length === 0) {
      // Fallback to any unused question in the bank
      candidates = QUESTION_BANK.filter(q => !usedIds.has(q.id));
    }

    const picked = candidates[Math.floor(Math.random() * candidates.length)];
    usedIds.add(picked.id);
    selectedQuestions.push(picked);
  }

  // Shuffle final 10 questions so category/difficulty order varies naturally
  return selectedQuestions.sort(() => Math.random() - 0.5).map(q => q.id);
}
